/**
 * D331 — generate the committed mailbox → owner seed from a Smartlead
 * GET /email-accounts backup taken BEFORE the client spaces were deleted.
 *
 *   npx tsx scripts/gen-mailbox-owner-seed.ts /path/to/email_accounts.json
 *
 * Writes data/mailbox-owner-seed.json and the embedded module
 * src/data/mailboxOwnerSeed.ts (id, from_email, slug only — no secrets).
 * JEREMY-CIOTOLA seats under 345263 are seeded `ciotola` (same legacy id).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { slugForLegacyClientId } from "../src/lib/ownership.js";

const input = process.argv[2];
if (!input) {
  console.error("usage: gen-mailbox-owner-seed.ts <email_accounts.json>");
  process.exit(1);
}
const accounts = JSON.parse(readFileSync(input, "utf8")) as Array<{
  id: number;
  from_email?: string;
  client_id?: number | null;
  tags?: Array<{ tag_name?: string }>;
}>;
const rows: Array<{ id: number; from_email: string; slug: string }> = [];
const unknown = new Map<number, number>();
for (const a of accounts) {
  if (typeof a.client_id !== "number") continue;
  let slug = slugForLegacyClientId(a.client_id);
  if (!slug) {
    unknown.set(a.client_id, (unknown.get(a.client_id) ?? 0) + 1);
    continue;
  }
  if (
    slug === "salesglider" &&
    (a.tags ?? []).some((t) => String(t.tag_name ?? "").toUpperCase() === "JEREMY-CIOTOLA")
  ) {
    slug = "ciotola";
  }
  rows.push({ id: a.id, from_email: String(a.from_email ?? "").toLowerCase(), slug });
}
if (unknown.size) {
  console.error("client ids with no catalog slug:", Object.fromEntries(unknown));
  process.exit(2);
}
rows.sort((x, y) => x.id - y.id);
const root = resolve(import.meta.dirname, "..");
writeFileSync(resolve(root, "data/mailbox-owner-seed.json"), JSON.stringify(rows, null, 1) + "\n");
const body = rows
  .map((r) => `  { id: ${r.id}, from_email: ${JSON.stringify(r.from_email)}, slug: ${JSON.stringify(r.slug)} },`)
  .join("\n");
writeFileSync(
  resolve(root, "src/data/mailboxOwnerSeed.ts"),
  `// AUTO-GENERATED by scripts/gen-mailbox-owner-seed.ts from the 2026-11-11
// Smartlead email-accounts backup (client_id before the client spaces were
// deleted, D331). Do not edit by hand. Embedded (not read from data/) for
// the same reason as genericPoolPlan.ts: Railpack may not ship data/.
export interface MailboxOwnerSeedRow {
  id: number;
  from_email: string;
  slug: string;
}

export const MAILBOX_OWNER_SEED_CAPTURED_AT = "2026-11-11";

export const MAILBOX_OWNER_SEED: readonly MailboxOwnerSeedRow[] = [
${body}
];
`,
);
console.log(`seed rows: ${rows.length}`);
