/**
 * D332 — pure helpers behind scripts/gen-mailbox-owner-seed.ts so the
 * regenerate / append rules are tested, not just documented.
 *
 * The seed is the D331 snapshot of who owned each mailbox when the client
 * spaces were deleted. It can only be rebuilt from a backup taken BEFORE the
 * deletion (every client_id after it is null), so regeneration refuses to
 * shrink the seed. New mailboxes normally go through POST /ownership/mailboxes
 * (override book); `--append` exists for a bulk backfill that should live in
 * the committed seed.
 */
import { ownerCatalogEntry, slugForLegacyClientId } from "./ownership.js";

export interface SeedRow {
  id: number;
  from_email: string;
  slug: string;
}

export interface BackupAccount {
  id: number;
  from_email?: string;
  client_id?: number | null;
  tags?: Array<{ tag_name?: string }>;
}

/** Seed rows from a pre-deletion GET /email-accounts backup. */
export function seedRowsFromBackup(accounts: readonly BackupAccount[]): {
  rows: SeedRow[];
  unknownClientIds: Record<number, number>;
} {
  const rows: SeedRow[] = [];
  const unknown: Record<number, number> = {};
  for (const a of accounts) {
    if (typeof a.client_id !== "number") continue;
    let slug = slugForLegacyClientId(a.client_id);
    if (!slug) {
      unknown[a.client_id] = (unknown[a.client_id] ?? 0) + 1;
      continue;
    }
    if (
      slug === "salesglider" &&
      (a.tags ?? []).some((t) => String(t.tag_name ?? "").toUpperCase() === "JEREMY-CIOTOLA")
    ) {
      slug = "ciotola";
    }
    rows.push({ id: a.id, from_email: String(a.from_email ?? "").toLowerCase(), slug });
  }
  rows.sort((x, y) => x.id - y.id);
  return { rows, unknownClientIds: unknown };
}

/**
 * A regenerate must not shrink the seed: a backup taken after the space
 * deletion has no client_id at all and would wipe 1,590 owners.
 */
export function assertSeedDoesNotShrink(next: readonly SeedRow[], current: readonly SeedRow[]): void {
  if (next.length < current.length) {
    throw new Error(
      `refusing to write ${next.length} seed rows over the current ${current.length}: ` +
        "the backup is probably from after the 2026-11-11 client-space deletion (client_id is null). " +
        "Use --append or POST /ownership/mailboxes for new mailboxes.",
    );
  }
}

/**
 * Merge new rows into the seed. A row whose id is already seeded with the
 * same slug is a no-op; a different slug is an error (the seed is never
 * reassigned). Slugs must be in OWNER_CATALOG.
 */
export function mergeSeedRows(
  current: readonly SeedRow[],
  additions: readonly unknown[],
): { rows: SeedRow[]; added: number; unchanged: number } {
  const byId = new Map(current.map((r) => [r.id, r]));
  let added = 0;
  let unchanged = 0;
  additions.forEach((raw, index) => {
    const r = (raw ?? {}) as Record<string, unknown>;
    const id = r.id;
    const slug = typeof r.slug === "string" ? r.slug.trim().toLowerCase() : "";
    const email = typeof r.from_email === "string" ? r.from_email.trim().toLowerCase() : "";
    if (typeof id !== "number" || !Number.isSafeInteger(id) || id <= 0) {
      throw new Error(`row ${index}: id must be a positive integer`);
    }
    if (!ownerCatalogEntry(slug)) throw new Error(`row ${index}: unknown slug ${JSON.stringify(r.slug)}`);
    if (!email.includes("@")) throw new Error(`row ${index}: from_email is required`);
    const existing = byId.get(id);
    if (existing) {
      if (existing.slug !== slug) {
        throw new Error(`row ${index}: mailbox ${id} is already seeded as ${existing.slug}; the seed is never reassigned`);
      }
      unchanged += 1;
      return;
    }
    byId.set(id, { id, from_email: email, slug });
    added += 1;
  });
  return { rows: [...byId.values()].sort((x, y) => x.id - y.id), added, unchanged };
}

export function renderSeedJson(rows: readonly SeedRow[]): string {
  return JSON.stringify(rows, null, 1) + "\n";
}

export function renderSeedModule(rows: readonly SeedRow[]): string {
  const body = rows
    .map((r) => `  { id: ${r.id}, from_email: ${JSON.stringify(r.from_email)}, slug: ${JSON.stringify(r.slug)} },`)
    .join("\n");
  return `// AUTO-GENERATED by scripts/gen-mailbox-owner-seed.ts from the 2026-11-11
// Smartlead email-accounts backup (client_id before the client spaces were
// deleted, D331). Do not edit by hand. Embedded (not read from data/) for
// the same reason as genericPoolPlan.ts: Railpack may not ship data/.
export interface MailboxOwnerSeedRow {
  id: number;
  from_email: string;
  slug: string;
}

export const MAILBOX_OWNER_SEED_CAPTURED_AT = "2026-11-11";

export const MAILBOX_OWNER_SEED: readonly MailboxOwnerSeedRow[] = [
${body}
];
`;
}

